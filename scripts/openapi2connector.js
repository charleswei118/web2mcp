#!/usr/bin/env node
// Convert an OpenAPI 3.x spec (JSON) into a web2mcp connector.
// Usage: node scripts/openapi2connector.js <spec.json | https://url/openapi.json> <name> [--only GET] [--base https://api.host] > connectors/<name>.js
import { readFile } from "node:fs/promises";

const [src, name, ...rest] = process.argv.slice(2);
if (!src || !name) {
  console.error("Usage: node scripts/openapi2connector.js <spec.json|url> <connector_name> [--only GET]");
  process.exit(1);
}
const only = rest.includes("--only") ? rest[rest.indexOf("--only") + 1].toUpperCase().split(",") : null;
const spec = JSON.parse(src.startsWith("http") ? await (await fetch(src)).text() : await readFile(src, "utf8"));
if (!String(spec.openapi || "").startsWith("3")) throw new Error("Only OpenAPI 3.x JSON is supported");

const slug = (s) => s.replace(/[^a-zA-Z0-9]+/g, "_").replace(/^_|_$/g, "").toLowerCase().slice(0, 32) || "op";
const resolve = (obj) => {
  if (obj && obj.$ref) return obj.$ref.replace(/^#\//, "").split("/").reduce((o, k) => o?.[k], spec);
  return obj;
};

const tools = [];
const seen = new Set();
for (const [rawPath, item] of Object.entries(spec.paths || {})) {
  for (const method of ["get", "post", "put", "patch", "delete"]) {
    const op = item[method];
    let path = rawPath;
    if (!op || (only && !only.includes(method.toUpperCase()))) continue;
    let tname = slug(op.operationId || `${method}_${path}`);
    while (seen.has(tname)) tname = (tname + "_x").slice(0, 32);
    seen.add(tname);
    const params = {};
    const query = {};
    for (const p0 of [...(item.parameters || []), ...(op.parameters || [])]) {
      const p = resolve(p0);
      if (!p || !["path", "query"].includes(p.in)) continue;
      const key = slug(p.name);
      const schema = resolve(p.schema) || {};
      params[key] = {
        type: ["integer", "number", "boolean"].includes(schema.type) ? schema.type : "string",
        description: (p.description || "").slice(0, 200) || undefined,
        required: p.required || p.in === "path" || undefined,
        enum: schema.enum,
        default: schema.default,
      };
      if (p.in === "query") query[p.name] = `{${key}}`;
      else if (key !== p.name) path = path.replaceAll(`{${p.name}}`, `{${key}}`);
    }
    const tool = {
      name: tname,
      description: (op.summary || op.description || `${method.toUpperCase()} ${path}`).replace(/\s+/g, " ").slice(0, 300),
      method: method.toUpperCase(),
      path,
      ...(Object.keys(query).length ? { query } : {}),
      params: JSON.parse(JSON.stringify(params)),
    };
    if (method !== "get" && op.requestBody) {
      tool.params.body = { type: "string", description: "JSON request body" };
      tool.body = "{body}";
    }
    tools.push(tool);
  }
}

function baseUrl() {
  if (rest.includes("--base")) return rest[rest.indexOf("--base") + 1];
  const u = spec.servers?.[0]?.url || "/";
  if (/^https?:/.test(u)) return u;
  if (src.startsWith("http")) return new URL(u, src).toString().replace(/\/$/, "");
  console.error(`Server URL "${u}" is relative: pass --base https://api.example.com`);
  return "https://example.com" + (u.startsWith("/") ? u : "/" + u);
}

const connector = {
  name: slug(name),
  title: spec.info?.title || name,
  description: (spec.info?.description || spec.info?.title || name).replace(/\s+/g, " ").slice(0, 300),
  baseUrl: baseUrl(),
  tools,
};
console.log(`// Generated by scripts/openapi2connector.js from ${src}\nexport default ${JSON.stringify(connector, null, 2)};`);
console.error(`Generated ${tools.length} tools. Review descriptions and add "pick"/"fields" to trim responses.`);
